#!/usr/bin/env python3
"""Verify that emacs-indigo and the reference Indigo agree on the corpus.

The golden files are generated by the reference mol2chemfigPy3 implementation
(epam.indigo).  The parity tests compare against those files using
emacs-indigo.  If the two Indigo builds disagree about a molecule's structure
(atoms, hydrogens, charges, radicals, bond orders, aromaticity), byte parity
would be meaningless.  This script computes a canonical SMILES for every corpus
MOL with both libraries and fails loudly on any divergence.

Run through tools/gen-goldens.py, which calls it before writing anything.
"""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "mol2chemfigPy3"))

CORPUS_DIR = os.path.join(ROOT, "test", "corpus")

from indigo import Indigo  # noqa: E402


def normalize(smiles):
    """Drop the CXSMILES extension block (radical/enhanced-stereo annotations).

    emacs-indigo writes ``... |^1:0|`` for radicals while the reference does
    not; the structural SMILES before the ``|`` is what we compare.
    """
    return smiles.split(" |")[0].strip()


def reference_perception(files):
    indigo = Indigo()
    result = {}
    for path in files:
        mol = indigo.loadMoleculeFromFile(path)
        result[os.path.basename(path)] = normalize(mol.canonicalSmiles())
    return result


def emacs_perception(files):
    command = [
        "emacs", "-Q", "--batch",
        "-L", ROOT,
        "-L", os.path.join(ROOT, "emacs-indigo"),
        "-l", os.path.join(ROOT, "tools", "dump-perception.el"),
    ] + files
    try:
        output = subprocess.run(
            command, check=True, capture_output=True, text=True
        ).stdout
    except FileNotFoundError:
        print("check-perception: emacs not found; skipping", file=sys.stderr)
        return None
    except subprocess.CalledProcessError as exc:
        raise SystemExit(f"check-perception: emacs failed:\n{exc.stderr}")
    result = {}
    for line in output.splitlines():
        if "\t" not in line:
            continue
        name, value = line.split("\t", 1)
        result[name] = normalize(value)
    return result


def main():
    files = sorted(
        os.path.join(CORPUS_DIR, name)
        for name in os.listdir(CORPUS_DIR)
        if name.endswith(".mol")
    )
    reference = reference_perception(files)
    emacs = emacs_perception(files)
    if emacs is None:
        return

    mismatches = []
    for name, ref_smiles in reference.items():
        emacs_smiles = emacs.get(name)
        if emacs_smiles != ref_smiles:
            mismatches.append((name, ref_smiles, emacs_smiles))

    if mismatches:
        print("Perception disagreement between emacs-indigo and reference:",
              file=sys.stderr)
        for name, ref_smiles, emacs_smiles in mismatches:
            print(f"  {name}\n    reference: {ref_smiles}\n    emacs:     {emacs_smiles}",
                  file=sys.stderr)
        raise SystemExit(1)

    print(f"perception check: {len(reference)} molecules agree")


if __name__ == "__main__":
    main()
